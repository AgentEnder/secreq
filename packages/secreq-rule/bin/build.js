#!/usr/bin/env node
// Compile a secreq rule written in AssemblyScript to a sandboxed core-wasm
// module the secreq daemon can load.
//
// Usage:
//   secreq-rule-build <rule.ts> -o <rule.wasm>
//   secreq-rule-build --raw <module.ts> -o <module.wasm>
//
// Default mode expects the rule file to export `decide(ctx: RuleCtx):
// Decision` and nothing else; this script generates a throwaway entry file
// next to the rule that wires that function through the ABI glue in
// ../assembly/abi.ts (exports `alloc` + the raw `decide(ptr, len)`), then
// invokes `asc` with the `stub` runtime so the output has no GC and no
// imports beyond AssemblyScript's `env.abort`.
//
// `--raw` skips the generated entry and compiles the file as-is — for
// modules that hand-implement the ABI (used by secreq's own test fixtures).

'use strict';

const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

function usage(msg) {
  if (msg) console.error(`secreq-rule-build: ${msg}`);
  console.error('usage: secreq-rule-build [--raw] <rule.ts> -o <rule.wasm>');
  process.exit(2);
}

function parseArgs(argv) {
  let raw = false;
  let input = null;
  let output = null;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--raw') raw = true;
    else if (arg === '-o' || arg === '--output') output = argv[++i];
    else if (arg.startsWith('-')) usage(`unknown flag ${arg}`);
    else if (input === null) input = arg;
    else usage('more than one input file');
  }
  if (!input) usage('missing input rule file');
  if (!output) usage('missing -o <rule.wasm>');
  return { raw, input: path.resolve(input), output: path.resolve(output) };
}

// Locate assemblyscript's asc entry point. Consumers install this package
// as a dependency, and npm does not install a dependency's devDependencies
// — so asc is found in the *consumer's* node_modules (resolved from their
// cwd), falling back to this package's own install (the in-repo fixture
// case, where rebuild.sh installs here).
function resolveAsc() {
  return require.resolve('assemblyscript/bin/asc.js', {
    paths: [process.cwd(), __dirname],
  });
}

// Relative import specifier from `fromDir` to ts file `to`, extension
// stripped, forward slashes (what asc's resolver expects).
function importSpecifier(fromDir, to) {
  let rel = path.relative(fromDir, to).replace(/\\/g, '/');
  rel = rel.replace(/\.ts$/, '');
  if (!rel.startsWith('.')) rel = './' + rel;
  return rel;
}

// Import specifier for the ABI glue in the generated entry. asc types are
// nominal and keyed by module identity, so this MUST match how the rule
// itself reached the SDK: a rule that wrote `import ... from "secreq-rule"`
// (the documented consumer form, resolved via node_modules) needs the entry
// to import the glue through the same package specifier, or `RuleCtx` /
// `Decision` split into two incompatible identities. Rules inside this repo
// (the test fixtures) import by relative path instead, and get a matching
// relative specifier.
function abiSpecifier(ruleDir, abiPath) {
  try {
    const viaPackage = path.dirname(
      require.resolve('secreq-rule/package.json', { paths: [ruleDir] }),
    );
    const thisPackage = path.join(__dirname, '..');
    if (fs.realpathSync(viaPackage) === fs.realpathSync(thisPackage)) {
      return 'secreq-rule/assembly/abi';
    }
  } catch (err) {
    // No resolvable secreq-rule package from the rule's directory — the
    // in-repo relative-import case. Anything else (e.g. an exports map
    // that hides ./package.json) must stay loud: falling back to a
    // relative specifier here would recreate the nominal-identity split
    // this function exists to prevent.
    if (err && err.code !== 'MODULE_NOT_FOUND') throw err;
  }
  return importSpecifier(ruleDir, abiPath);
}

function main() {
  const { raw, input, output } = parseArgs(process.argv.slice(2));
  if (!fs.existsSync(input)) usage(`input not found: ${input}`);

  const ascFlags = [
    '--runtime',
    'stub',
    '--optimizeLevel',
    '2',
    '--shrinkLevel',
    '0',
    '--outFile',
    output,
  ];

  let entry = input;
  let generated = null;
  if (!raw) {
    const ruleDir = path.dirname(input);
    const base = path.basename(input, '.ts');
    const abi = path.join(__dirname, '..', 'assembly', 'abi.ts');
    // pid-suffixed so concurrent builds of the same rule can't delete each
    // other's entry mid-compile.
    generated = path.join(ruleDir, `.secreq-entry.${base}.${process.pid}.ts`);
    fs.writeFileSync(
      generated,
      `// Generated by secreq-rule-build — do not edit, do not commit.
import { decide as rule } from ${JSON.stringify(importSpecifier(ruleDir, input))};
import { allocBytes, readCtx, encodeDecision } from ${JSON.stringify(abiSpecifier(ruleDir, abi))};

export function alloc(len: i32): usize {
  return allocBytes(len);
}

export function decide(ptr: usize, len: i32): u64 {
  return encodeDecision(rule(readCtx(ptr, len)));
}
`,
    );
    entry = generated;
  }

  try {
    execFileSync(process.execPath, [resolveAsc(), entry, ...ascFlags], { stdio: 'inherit' });
  } finally {
    if (generated) fs.rmSync(generated, { force: true });
  }
}

main();
