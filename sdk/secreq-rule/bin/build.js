#!/usr/bin/env node
// Compile a secreq rule written in AssemblyScript to a sandboxed core-wasm
// module the secreq daemon can load.
//
// Usage:
//   secreq-rule-build <rule.ts> -o <rule.wasm>
//   secreq-rule-build --raw <module.ts> -o <module.wasm>
//
// Default mode expects the rule file to export `decide(ctx: RuleCtx):
// Decision` and nothing else; this script generates a throwaway entry file
// next to the rule that wires that function through the ABI glue in
// ../assembly/abi.ts (exports `alloc` + the raw `decide(ptr, len)`), then
// invokes `asc` with the `stub` runtime so the output has no GC and no
// imports beyond AssemblyScript's `env.abort`.
//
// `--raw` skips the generated entry and compiles the file as-is — for
// modules that hand-implement the ABI (used by secreq's own test fixtures).

"use strict";

const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

function usage(msg) {
  if (msg) console.error(`secreq-rule-build: ${msg}`);
  console.error("usage: secreq-rule-build [--raw] <rule.ts> -o <rule.wasm>");
  process.exit(2);
}

function parseArgs(argv) {
  let raw = false;
  let input = null;
  let output = null;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--raw") raw = true;
    else if (arg === "-o" || arg === "--output") output = argv[++i];
    else if (arg.startsWith("-")) usage(`unknown flag ${arg}`);
    else if (input === null) input = arg;
    else usage("more than one input file");
  }
  if (!input) usage("missing input rule file");
  if (!output) usage("missing -o <rule.wasm>");
  return { raw, input: path.resolve(input), output: path.resolve(output) };
}

// Relative import specifier from `fromDir` to ts file `to`, extension
// stripped, forward slashes (what asc's resolver expects).
function importSpecifier(fromDir, to) {
  let rel = path.relative(fromDir, to).replace(/\\/g, "/");
  rel = rel.replace(/\.ts$/, "");
  if (!rel.startsWith(".")) rel = "./" + rel;
  return rel;
}

function main() {
  const { raw, input, output } = parseArgs(process.argv.slice(2));
  if (!fs.existsSync(input)) usage(`input not found: ${input}`);

  const ascFlags = [
    "--runtime",
    "stub",
    "--optimizeLevel",
    "2",
    "--shrinkLevel",
    "0",
    "--outFile",
    output,
  ];

  let entry = input;
  let generated = null;
  if (!raw) {
    const ruleDir = path.dirname(input);
    const base = path.basename(input, ".ts");
    const abi = path.join(__dirname, "..", "assembly", "abi.ts");
    generated = path.join(ruleDir, `.secreq-entry.${base}.ts`);
    fs.writeFileSync(
      generated,
      `// Generated by secreq-rule-build — do not edit, do not commit.
import { decide as rule } from ${JSON.stringify(importSpecifier(ruleDir, input))};
import { allocBytes, readCtx, encodeDecision } from ${JSON.stringify(importSpecifier(ruleDir, abi))};

export function alloc(len: i32): usize {
  return allocBytes(len);
}

export function decide(ptr: usize, len: i32): u64 {
  return encodeDecision(rule(readCtx(ptr, len)));
}
`
    );
    entry = generated;
  }

  try {
    execFileSync(
      process.execPath,
      [require.resolve("assemblyscript/bin/asc.js"), entry, ...ascFlags],
      { stdio: "inherit" }
    );
  } finally {
    if (generated) fs.rmSync(generated, { force: true });
  }
}

main();
